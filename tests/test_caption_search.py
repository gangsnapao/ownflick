"""Module M1: caption search on the media index.

The media_items index carries a cleaned `caption` column generated by
caption_text.format_caption at write time; search matches filename, rel_path
or caption so a query can hit items whose file names do not contain the
caption text (e.g. aliased captions later).
"""

from pathlib import Path

from spooly.services.caption_text import format_caption
from spooly.services.database import AppDatabase
from spooly.services.library import LibraryService, MediaSource
from spooly.services.library_index import LibraryIndexer, MediaIndexStore


def build_env(tmp_path, names):
    root = tmp_path / 'media'
    for name in names:
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b'media')
    library = LibraryService(
        media_sources=[MediaSource('default', 'Default', root)],
    )
    database = AppDatabase(tmp_path / 'state' / 'caption.sqlite3')
    database.migrate()
    media_index = MediaIndexStore(database)
    LibraryIndexer(library, media_index).sync()
    return root, library, media_index, database


def test_caption_column_generated_from_filename(tmp_path):
    _, _, media_index, database = build_env(
        tmp_path, ['2022-12-30 17.15.06 海边旅行_88.mp4'],
    )
    with database.connect() as conn:
        row = conn.execute(
            "SELECT filename, caption FROM media_items"
        ).fetchone()
    assert row['caption'] == format_caption(row['filename'])
    assert row['caption'] == '海边旅行'


def test_search_hits_caption_column(tmp_path):
    _, _, media_index, database = build_env(tmp_path, ['open/keep.mp4', 'open/other.jpg'])
    # Simulate an aliased caption: the file name does not contain the term.
    with database.connect() as conn:
        conn.execute(
            "UPDATE media_items SET caption = '独有文案词' WHERE uri = ?",
            ('@default/open/keep.mp4',),
        )
    rows = media_index.records(search='独有文案词')
    assert {row['name'] for row in rows} == {'@default/open/keep.mp4'}
    assert media_index.records(search='不存在的词') == []


def test_search_still_hits_filename_and_relpath(tmp_path):
    _, _, media_index, _ = build_env(tmp_path, ['open/keep.mp4', 'open/other.jpg'])
    assert {row['name'] for row in media_index.records(search='keep')} == {'@default/open/keep.mp4'}
    assert {row['name'] for row in media_index.records(search='open')} == {
        '@default/open/keep.mp4', '@default/open/other.jpg',
    }


def test_replace_snapshot_refreshes_caption(tmp_path):
    root, library, media_index, database = build_env(tmp_path, ['2022-01-01 初版_1.mp4'])
    assert media_index.records(search='初版')
    # Rename the file out-of-band and resync: the caption follows the new name.
    old = root / '2022-01-01 初版_1.mp4'
    new = root / '2022-01-02 改版文案_2.mp4'
    old.rename(new)
    LibraryIndexer(library, media_index).sync()
    assert not media_index.records(search='初版')
    assert {row['name'] for row in media_index.records(search='改版文案')} == {'@default/2022-01-02 改版文案_2.mp4'}


def test_migration_backfills_existing_rows(tmp_path):
    root, library, media_index, database = build_env(
        tmp_path, ['2022-12-30 17.15.06 海边旅行_88.mp4'],
    )
    # Blank the caption, then run the backfill step directly (migrations are
    # recorded as applied and do not re-run on migrate()).
    from spooly.services.database import _migrate_014_add_media_item_caption

    with database.connect() as conn:
        conn.execute("UPDATE media_items SET caption = ''")
        _migrate_014_add_media_item_caption(conn)
        row = conn.execute("SELECT caption FROM media_items").fetchone()
    assert row['caption'] == '海边旅行'
